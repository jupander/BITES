"""
Tests for bites.utils.toothmaker_format module.

Covers:
- parse_format1(): parsing tooth model parameter files
- write_format2(): writing ToothMaker-compatible parameter files
"""

import pytest

from bites.utils.toothmaker_format import parse_format1, write_format2


# ---------------------------------------------------------------------------
# parse_format1
# ---------------------------------------------------------------------------

class TestParseFormat1:
    """Tests for parse_format1()."""

    def test_parses_parameters(self, tmp_path):
        """Extracts (name, value) pairs from a format1 file."""
        content = (
            "0.025 Egr\n"
            "200.0 Mgr\n"
            "0.22 Act\n"
        )
        f = tmp_path / "params.txt"
        f.write_text(content, encoding="utf-8")

        params, iters = parse_format1(str(f))
        assert len(params) == 3
        assert params[0] == ("Egr", 0.025)
        assert params[1] == ("Mgr", 200.0)
        assert params[2] == ("Act", 0.22)

    def test_extracts_iterations(self, tmp_path):
        """Extracts number of iterations from the file."""
        content = (
            "0.025 Egr\n"
            "5000 number of iterations\n"
        )
        f = tmp_path / "params.txt"
        f.write_text(content, encoding="utf-8")

        params, iters = parse_format1(str(f))
        assert iters == 5000
        assert len(params) == 1

    def test_skips_dash_params(self, tmp_path):
        """Skips '-' placeholder parameters."""
        content = (
            "0.025 Egr\n"
            "0.0 -\n"
            "200.0 Mgr\n"
        )
        f = tmp_path / "params.txt"
        f.write_text(content, encoding="utf-8")

        params, _ = parse_format1(str(f))
        names = [name for name, _ in params]
        assert "-" not in names
        assert len(params) == 2

    def test_skips_number_keyword(self, tmp_path):
        """Skips lines where name is 'number' (cell count lines)."""
        content = (
            "0.025 Egr\n"
            "1000 number\n"
        )
        f = tmp_path / "params.txt"
        f.write_text(content, encoding="utf-8")

        params, _ = parse_format1(str(f))
        names = [name for name, _ in params]
        assert "number" not in names

    def test_empty_file_returns_empty(self, tmp_path):
        """Empty file returns empty list and None iterations."""
        f = tmp_path / "empty.txt"
        f.write_text("", encoding="utf-8")

        params, iters = parse_format1(str(f))
        assert params == []
        assert iters is None

    def test_blank_lines_skipped(self, tmp_path):
        """Blank lines are ignored."""
        content = (
            "\n"
            "0.025 Egr\n"
            "\n"
            "200.0 Mgr\n"
            "\n"
        )
        f = tmp_path / "params.txt"
        f.write_text(content, encoding="utf-8")

        params, _ = parse_format1(str(f))
        assert len(params) == 2

    def test_no_iterations_returns_none(self, tmp_path):
        """File without iteration line returns None for iterations."""
        content = "0.025 Egr\n200.0 Mgr\n"
        f = tmp_path / "params.txt"
        f.write_text(content, encoding="utf-8")

        _, iters = parse_format1(str(f))
        assert iters is None


