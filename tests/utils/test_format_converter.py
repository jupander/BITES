class TestWriteFormat2:
    """Tests for write_format2()."""

    def test_writes_file(self, tmp_path):
        """Creates an output file."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025)], str(out), iterations=5000)
        assert out.exists()

    def test_contains_header_comment(self, tmp_path):
        """Output contains header comment."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025)], str(out), iterations=5000)
        content = out.read_text(encoding="utf-8")
        assert "Model parameters file generated by BITES" in content

    def test_contains_model_line(self, tmp_path):
        """Output contains model name line."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025)], str(out), iterations=5000)
        content = out.read_text(encoding="utf-8")
        assert "model==Tribosphenic tooth" in content

    def test_contains_iterations(self, tmp_path):
        """Output contains iterations value."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025)], str(out), iterations=5000)
        content = out.read_text(encoding="utf-8")
        assert "iter==5000" in content

    def test_contains_parameters_with_separator(self, tmp_path):
        """Output contains parameter lines with '==' separator."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025), ("Mgr", 200.0)], str(out), iterations=5000)
        content = out.read_text(encoding="utf-8")
        assert "Egr==0.0250000" in content
        assert "Mgr==200.0000000" in content

    def test_default_iterations_when_none(self, tmp_path):
        """Uses default_iterations when iterations is None."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025)], str(out), iterations=None,
                      default_iterations=9000)
        content = out.read_text(encoding="utf-8")
        assert "iter==9000" in content

    def test_custom_default_iterations(self, tmp_path):
        """Custom default_iterations value is used."""
        out = tmp_path / "out.txt"
        write_format2([], str(out), iterations=None, default_iterations=12000)
        content = out.read_text(encoding="utf-8")
        assert "iter==12000" in content

    def test_unix_line_endings(self, tmp_path):
        """Output uses Unix line endings (\\n not \\r\\n)."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025)], str(out), iterations=5000)
        raw = out.read_bytes()
        assert b"\r\n" not in raw

    def test_utf8_encoding(self, tmp_path):
        """Output is UTF-8 encoded."""
        out = tmp_path / "out.txt"
        write_format2([("Egr", 0.025)], str(out), iterations=5000)
        # Reading with utf-8 should not raise
        out.read_text(encoding="utf-8")
