from pathlib import Path
from typing import List, Tuple, Optional


def parse_format1(file_path: str) -> Tuple[List[Tuple[str, float]], Optional[int]]:
    """
    Parse format 1 parameter file.
    
    Args:
        file_path: Path to the input file
        
    Returns:
        Tuple of (parameters list, number of iterations)
    """
    parameters = []
    num_iterations = None
    
    # Ensure UTF-8 encoding when reading
    with open(file_path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            stripped = line.strip()
            
            # Skip empty lines
            if not stripped:
                continue
            
            # Check for iterations
            if "number of iterations" in stripped.lower():
                try:
                    num_iterations = int(stripped.split()[0])
                except (ValueError, IndexError) as e:
                    print(f"Warning: Could not parse iterations on line {line_num}: {e}")
                continue
            
            # Parse parameter lines
            parts = stripped.split()
            if len(parts) < 2:
                continue
                
            try:
                value = float(parts[0])
                name = parts[1]
                
                # Skip empty params and 'number of cells'
                if name not in ['-', 'number']:
                    parameters.append((name, value))
            except (ValueError, IndexError):
                print(f"Warning: Could not parse parameter on line {line_num}: '{stripped}'")
                continue
    
    return parameters, num_iterations


def write_format2(
    parameters: List[Tuple[str, float]], 
    output_path: str, 
    iterations: Optional[int],
    default_iterations: int = 9000
) -> None:
    """
    Write parameters in format 2, i.e. one importable to the ToothMaker interface.
    
    Args:
        parameters: List of (name, value) tuples
        output_path: Path to the output file
        iterations: Number of iterations (None for default)
        default_iterations: Default iteration value if none provided
    """
    # Ensure UTF-8 encoding and Unix line endings (without UTF-8, ToothMaker gives errors, on Windows+WSL at least)
    with open(output_path, 'w', encoding='utf-8', newline='\n') as f:
        # Write header
        f.write("# Model parameters file generated by BITES. (This text file format is compatible/importable with ToothMaker, the other one with BITES Config Editor)\n")
        f.write("# NOTE: Parameter names are case-sensitive, while non-parameter keywords\n")
        f.write("# (e.g. model, viewtresh) are case-insensitive!\n\n")
        
        # Write model configuration
        f.write("# Model name, view threshold, view mode, iterations.\n")
        f.write("model==Tribosphenic tooth\n")
        f.write("viewthresh==0.080000\n")
        f.write("viewmode==4\n")
        
        iter_value = iterations if iterations is not None else default_iterations
        f.write(f"iter=={iter_value}\n\n")
        
        # Write parameters
        f.write("# Parameters.\n")
        for name, value in parameters:
            f.write(f"{name}=={value:.7f}\n")


def main(input_file: str, output_file: str) -> None:
    """Main execution function."""

    
    # Check if input file exists
    if not Path(input_file).exists():
        print(f"Error: Input file '{input_file}' not found.")
        return
    
    try:
        # Parse and convert
        params, num_iters = parse_format1(input_file)
        write_format2(params, output_file, num_iters)
        
        # Report results
        print(f" Converted {len(params)} parameters to format 2")
        print(f" Iterations: {num_iters if num_iters else 'default (9000)'}")
        print(f" Output written to: {output_file}")
        
    except Exception as e:
        print(f"Error during conversion: {e}")
        raise

if __name__ == "__main__":
    import sys
    
    if len(sys.argv) < 3:
        print("Usage: python format_from_tooth_model_to_toothmaker.py <input_txt_file>, <output_txt_file>")
        sys.exit(1)
    
    input_file = sys.argv[1]
